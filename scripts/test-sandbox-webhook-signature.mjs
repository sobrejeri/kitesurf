import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
import { verifySandboxWebhookSignature as verify } from '../src/lib/sandbox-webhook-signature.mjs';
const secret = 'sandbox-fixture-secret';
const ts = '1794450000000';
const requestId = 'request-fixture';
const dataId = 'payment-fixture';
const manifest = `id:${dataId};request-id:${requestId};ts:${ts};`;
const v1 = createHmac('sha256', secret).update(manifest).digest('hex');
const base = { signature: `ts=${ts},v1=${v1}`, requestId, dataId, secret, nowMs: Number(ts) };
assert.equal(verify(base), true);
assert.equal(verify({ ...base, requestId: 'other' }), false);
assert.equal(verify({ ...base, dataId: 'other' }), false);
assert.equal(verify({ ...base, secret: 'other' }), false);
assert.equal(verify({ ...base, nowMs: Number(ts) + 300001 }), false);
assert.equal(verify({ ...base, signature: `ts=${ts},v1=${'0'.repeat(64)}` }), false);
assert.equal(verify({ ...base, signature: `ts=${ts},ts=${ts},v1=${v1}` }), false);
assert.equal(verify({ ...base, signature: 'ts=abc,v1=' + v1 }), false);
assert.equal(verify({ ...base, signature: 'ts=' + ts }), false);
console.log('Sandbox signed webhook verification passed');
