import assert from 'node:assert/strict';
import {studentHomeSummary} from '../src/lib/student-home.ts';
const now=Date.parse('2026-11-05T15:00:00Z');
const meeting=(id,status,starts_at,done_minutes=0)=>({id,status,starts_at,done_minutes,minutes:60,position:1,note:null});
const booking=(id,status,meetings,total_hours=2)=>({id,status,booking_meetings:meetings,total_hours,created_at:'2026-11-05T14:55:00Z'});
const old=booking('old','confirmed',[meeting('past','scheduled','2026-11-04T13:00:00Z')]);
const next=booking('next','confirmed',[meeting('future','scheduled','2026-11-06T13:00:00Z'),meeting('done','done','2026-11-04T13:00:00Z',45)]);
const later=booking('later','confirmed',[meeting('later-meeting','scheduled','2026-11-09T13:00:00Z')],6);
const done=booking('done','completed',[meeting('recorded','done','2026-10-01T13:00:00Z',60)],1);
const cancelled=booking('cancelled','cancelled',[meeting('cancelled-date','scheduled','2026-11-05T16:00:00Z')]);
let result=studentHomeSummary([old,later,next,done,cancelled],now);
assert.equal(result.current.booking.id,'next','A past unrecorded meeting cannot masquerade as next class');
assert.equal(result.unrecorded.length,1);
assert.equal(result.recordedMinutes,45,'Use real minutes, not elapsed time or completed meeting count');
assert.equal(result.totalMinutes,120,'Never pool hours from different bookings');
assert.equal(result.remainingMinutes,75);
assert.equal(result.upcoming.length,2);
const ongoing=booking('ongoing','confirmed',[meeting('active','in_progress','2026-11-04T13:00:00Z')]);
assert.equal(studentHomeSummary([next,ongoing],now).current.booking.id,'ongoing');
assert.equal(studentHomeSummary([done],now).percent,100);
assert.equal(studentHomeSummary([],now).current,null);
const expired=booking('expired','awaiting_payment',[]);expired.created_at='2026-11-05T12:00:00Z';
assert.deepEqual(studentHomeSummary([expired,booking('valid','awaiting_payment',[])],now).pending.map(b=>b.id),['valid']);
console.log('PASS: personal home keeps booking hours separate, handles pending/expired/ongoing/past/future classes');
