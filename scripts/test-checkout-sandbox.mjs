import assert from 'node:assert/strict';
import { calculateSandboxQuote, nextSandboxStatus, sandboxIdempotencyKey } from '../src/lib/checkout-sandbox.ts';
const id = '123e4567-e89b-42d3-a456-426614174000';
const quote = calculateSandboxQuote(id, 45000, 1500);
assert.deepEqual([quote.platformFeeCents, quote.instructorCents, quote.partnerCents], [6750, 38250, 0]);
const affiliate = calculateSandboxQuote(id, 45000, 1500, 500);
assert.equal(affiliate.platformFeeCents + affiliate.partnerCents + affiliate.instructorCents, 45000);
for (const value of [-1, 0, 1.5, NaN, Infinity, Number.MAX_SAFE_INTEGER]) assert.throws(() => calculateSandboxQuote(id, value, 1500));
for (const rate of [-1, 10001, 0.5, NaN]) assert.throws(() => calculateSandboxQuote(id, 45000, rate));
assert.throws(() => calculateSandboxQuote(id, 45000, 8000, 3000));
assert.equal(nextSandboxStatus('created', 'pending'), 'pending');
assert.equal(nextSandboxStatus('pending', 'approved'), 'approved');
assert.equal(nextSandboxStatus('approved', 'approved'), 'approved');
assert.equal(nextSandboxStatus('approved', 'refunded'), 'refunded');
assert.throws(() => nextSandboxStatus('refunded', 'approved'));
assert.throws(() => nextSandboxStatus('declined', 'approved'));
assert.equal(sandboxIdempotencyKey('pagarme', 'event_12345678'), 'pagarme:event_12345678');
assert.throws(() => sandboxIdempotencyKey('pagarme', '../unsafe'));
console.log('PASS: offline checkout quote, split conservation, state transitions, event IDs');
