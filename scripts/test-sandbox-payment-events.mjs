import assert from 'node:assert/strict';
import { newSandboxPayment, applySandboxPaymentEvent } from '../src/lib/sandbox-payment-events.mjs';
const event = (paymentId, eventId, status) => ({ paymentId, eventId, status });
const pix = newSandboxPayment({ paymentId: 'p1', method: 'pix' });
const paid = applySandboxPaymentEvent(pix, event('p1', 'e1', 'approved'));
assert.equal(paid.status, 'approved');
assert.equal(paid.payoutStatus, 'not_started');
assert.deepEqual(applySandboxPaymentEvent(paid, event('p1', 'e1', 'approved')), paid);
const refunded = applySandboxPaymentEvent(paid, event('p1', 'e2', 'refunded'));
assert.equal(refunded.status, 'refunded');
assert.equal(refunded.payoutStatus, 'not_started');
assert.deepEqual(applySandboxPaymentEvent(refunded, event('p1', 'e1', 'approved')), refunded);
assert.throws(() => applySandboxPaymentEvent(refunded, event('p1', 'e3', 'approved')));
assert.throws(() => applySandboxPaymentEvent(pix, event('other', 'e1', 'approved')));
assert.throws(() => applySandboxPaymentEvent(pix, event('p1', 'e1', 'declined')));
const expired = applySandboxPaymentEvent(pix, event('p1', 'e2', 'expired'));
assert.equal(expired.status, 'expired');
assert.throws(() => applySandboxPaymentEvent(expired, event('p1', 'e3', 'approved')));
const card = newSandboxPayment({ paymentId: 'c1', method: 'card' });
assert.equal(applySandboxPaymentEvent(card, event('c1', 'c2', 'declined')).status, 'declined');
assert.equal(applySandboxPaymentEvent(card, event('c1', 'c3', 'approved')).status, 'approved');
assert.throws(() => applySandboxPaymentEvent(card, event('c1', 'c4', 'expired')));
assert.throws(() => newSandboxPayment({ paymentId: 'c1', method: 'boleto' }));
assert.throws(() => applySandboxPaymentEvent(card, event('c1', '', 'approved')));
console.log('Sandbox payment event idempotency and state transitions passed');
