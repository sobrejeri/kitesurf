import assert from 'node:assert/strict';
import { applySandboxPaymentEvent } from '../src/lib/checkout-event-replay.ts';
let state = { status: 'created', paymentId: 'pay_test_123', processedEventKeys: [] };
const pending = { provider: 'pagarme', eventId: 'event_12345678', nextStatus: 'pending', paymentId: 'pay_test_123' };
let result = applySandboxPaymentEvent(state, pending);
assert.equal(result.applied, true);
assert.equal(result.state.status, 'pending');
state = result.state;
result = applySandboxPaymentEvent(state, pending);
assert.equal(result.applied, false);
assert.equal(result.state, state, 'Replay must not mutate state');
result = applySandboxPaymentEvent(state, { provider: 'pagarme', eventId: 'event_87654321', nextStatus: 'approved', paymentId: 'pay_test_123' });
assert.equal(result.state.status, 'approved');
state = result.state;
assert.throws(() => applySandboxPaymentEvent(state, { provider: 'pagarme', eventId: 'event_33333333', nextStatus: 'pending', paymentId: 'pay_test_123' }), 'Out-of-order regression rejected');
assert.equal(state.status, 'approved', 'Rejected event must not mutate prior state');
result = applySandboxPaymentEvent(state, { provider: 'pagarme', eventId: 'event_44444444', nextStatus: 'refunded', paymentId: 'pay_test_123' });
assert.equal(result.state.status, 'refunded');
assert.throws(() => applySandboxPaymentEvent(result.state, { provider: 'pagarme', eventId: 'event_55555555', nextStatus: 'approved', paymentId: 'pay_test_123' }));
assert.throws(() => applySandboxPaymentEvent(state, { provider: 'pagarme', eventId: 'bad', nextStatus: 'refunded', paymentId: 'pay_test_123' }));
console.log('PASS: offline payment event replay, duplicates, ordering and terminal states');

assert.throws(() => applySandboxPaymentEvent(state, { provider: 'pagarme', eventId: 'event_99999999', nextStatus: 'refunded', paymentId: 'pay_other_456' }), 'Cross-payment event must fail closed');
